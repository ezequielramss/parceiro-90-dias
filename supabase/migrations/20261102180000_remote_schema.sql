CREATE OR REPLACE FUNCTION "public"."handle_new_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  insert into public.funcionarios (id_funcionarios, nome)
  values (
    new.id, 
    coalesce(new.raw_user_meta_data ->> 'nome', new.email)
  );
  return new;
end;
$$;


